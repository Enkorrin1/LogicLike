extension LocalizedContent on AppLocalizations {
  String childAgeLabel(ChildAge age) => ageYears(age.years);

  String languageName(AppLanguage language) {
    return switch (language) {
      AppLanguage.ar => 'العربية',
      AppLanguage.de => 'Deutsch',
      AppLanguage.en => 'English',
      AppLanguage.es => 'Español',
      AppLanguage.fr => 'Français',
      AppLanguage.hi => 'हिन्दी',
      AppLanguage.it => 'Italiano',
      AppLanguage.ja => '日本語',
      AppLanguage.ko => '한국어',
      AppLanguage.pt => 'Português',
      AppLanguage.ru => 'Русский',
      AppLanguage.zh => '中文',
    };
  }

  String areaTitle(String areaId) =>
      _lookup(_areaTitles, areaId) ?? _lookup(_areaTitles, 'logic')!;

  String areaSubtitle(String areaId) =>
      _lookup(_areaSubtitles, areaId) ?? _lookup(_areaSubtitles, 'logic')!;

  String puzzleTitle(LearningPuzzle puzzle) =>
      _puzzleCopy(puzzle.id)?.title ?? puzzle.title;

  String puzzlePrompt(LearningPuzzle puzzle) {
    final language = localeName.split('_').first;
    return _activePuzzlePromptOverrides[language]?[puzzle.id] ??
        _puzzleCopy(puzzle.id)?.prompt ??
        puzzle.prompt;
  }

  String puzzleSkill(LearningPuzzle puzzle) =>
      _puzzleCopy(puzzle.id)?.skill ?? puzzle.skill;

  String retryTextForPuzzle(LearningPuzzle puzzle, String fallback) {
    final localized = _lookupCurrentLocale(_newRetryText, puzzle.id) ??
        _lookupCurrentLocale(_retryText, puzzle.id);
    if (localized != null) {
      return localized;
    }

    if (localeName.split('_').first == 'ru') {
      return fallback;
    }

    return hintForArea(puzzle.areaId);
  }

  String answerLabel(String source) {
    final localized = _lookupCurrentLocale(_newAnswerLabels, source);
    if (localized != null) {
      return localized;
    }

    if (!_containsCyrillic(source)) {
      return source;
    }

    return _lookupCurrentLocale(_answerLabels, source) ?? source;
  }

  String hintForArea(String areaId) {
    return switch (areaId) {
      'memory' => hintMemory,
      'attention' => hintAttention,
      'math' => hintMath,
      'space' => hintSpace,
      _ => hintLogic,
    };
  }

  String collectionItemTitle(String itemId) {
    return _lookup(_collectionTitles, itemId) ?? itemId;
  }

  String collectionItemSubtitle(String itemId) {
    return _lookup(_collectionSubtitles, itemId) ?? itemId;
  }

  String mapNodeTitle(int order) {
    return switch (order) {
      1 => homeMapStart,
      2 => homeMapShapes,
      3 => homeMapPairs,
      4 => homeMapCount,
      5 => homeMapPath,
      6 => homeMapRhythm,
      7 => homeMapCompare,
      _ => homeMapFinal,
    };
  }

  String? _lookup(Map<String, Map<String, String>> source, String key) {
    final language = localeName.split('_').first;
    return source[language]?[key] ?? source['en']?[key];
  }

  String? _lookupCurrentLocale(
    Map<String, Map<String, String>> source,
    String key,
  ) {
    final language = localeName.split('_').first;
    return source[language]?[key];
  }

  _PuzzleCopy? _puzzleCopy(String puzzleId) {
    final language = localeName.split('_').first;
    return _newPuzzles[language]?[puzzleId] ??
        _newPuzzles['en']?[puzzleId] ??
        _puzzles[language]?[puzzleId] ??
        _puzzles['en']?[puzzleId] ??
        _puzzles['ru']?[puzzleId];
  }
}

bool hasLocalizedPuzzleCopy(String languageCode, String puzzleId) {
  return (_newPuzzles[languageCode]?.containsKey(puzzleId) ?? false) ||
      (_puzzles[languageCode]?.containsKey(puzzleId) ?? false);
}

bool _containsCyrillic(String value) {
  return value.runes.any(
    (rune) =>
        (rune >= 0x0400 && rune <= 0x04ff) ||
        (rune >= 0x0500 && rune <= 0x052f) ||
        (rune >= 0x2de0 && rune <= 0x2dff) ||
        (rune >= 0xa640 && rune <= 0xa69f),
  );
}

